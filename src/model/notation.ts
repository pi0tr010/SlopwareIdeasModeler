import type { Marker, ShapeKind } from "./registry";

/** A node or a connector that has its own notation, so the diagram is no longer "basic shapes". */
export type NodePick = { shape: ShapeKind; w: number; h: number; container?: boolean; stereotype?: string };
export type EdgePick = { edge: true; dashed?: boolean; start?: Marker; end?: Marker };
export type Pick = NodePick | EdgePick;

const n = (shape: ShapeKind, w: number, h: number, extra?: Partial<NodePick>): NodePick => ({ shape, w, h, ...extra });
const e = (end: Marker = "open-arrow", dashed = false, start: Marker = "none"): EdgePick => ({ edge: true, dashed, start, end });

const nodes = (shape: ShapeKind, w: number, h: number, ids: string[], extra?: Partial<NodePick>) =>
  Object.fromEntries(ids.map((id) => [id, n(shape, w, h, extra)])) as Record<string, NodePick>;
const edges = (ids: string[], end: Marker = "open-arrow", dashed = false) =>
  Object.fromEntries(ids.map((id) => [id, e(end, dashed)])) as Record<string, EdgePick>;

