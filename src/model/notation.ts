/** Notation for the diagrams that were still drawn with generic shapes. */
export function notationOf(type: string): Pick | undefined {
  if (MAP[type]) return MAP[type];
  if (type === "circuit-wire") return e("none");
  if (type.startsWith("circuit-")) return n("symbol", 72, type.includes("transistor") || type.includes("gate") ? 64 : 48);
  return undefined;
}
