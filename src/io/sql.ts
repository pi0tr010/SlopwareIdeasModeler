import type { Diagram, ErdAttribute, ModelElement, Project } from "../model/types";

export type SqlDialect = "postgresql" | "mysql" | "sqlite" | "mssql" | "oracle";

export const SQL_DIALECTS: { id: SqlDialect; name: string }[] = [
  { id: "postgresql", name: "PostgreSQL" },
  { id: "mysql", name: "MySQL / MariaDB" },
  { id: "sqlite", name: "SQLite" },
  { id: "mssql", name: "Microsoft SQL Server" },
  { id: "oracle", name: "Oracle" },
];

const quote = (d: SqlDialect, name: string) => {
  if (d === "mysql") return "`" + name + "`";
  if (d === "mssql") return "[" + name + "]";
  return '"' + name + '"';
};

function columnType(d: SqlDialect, a: ErdAttribute): string {
  const t = a.type || "varchar";
  const size = a.size && a.size.toUpperCase() !== "MAX" ? `(${a.size})` : a.size?.toUpperCase() === "MAX" ? (d === "mssql" ? "(MAX)" : "") : "";
  const lower = t.toLowerCase();
  if (d === "postgresql") {
    if (a.autoIncrement && /int/.test(lower)) return lower === "bigint" ? "BIGSERIAL" : "SERIAL";
    if (lower === "nvarchar") return a.size?.toUpperCase() === "MAX" ? "TEXT" : `VARCHAR${size}`;
    if (lower === "datetime") return "TIMESTAMP";
  }
  if (d === "sqlite") {
    if (/int/.test(lower)) return "INTEGER";
    if (/char|text|clob/.test(lower)) return "TEXT";
    if (/real|floa|doub|decimal|numeric/.test(lower)) return "REAL";
  }
  if (d === "oracle" && /varchar/.test(lower)) return `VARCHAR2${size || "(255)"}`;
  if (d === "mysql" && lower === "nvarchar" && a.size?.toUpperCase() === "MAX") return "LONGTEXT";
  return t.toUpperCase() + size;
}

function entitiesOf(project: Project, diagram?: Diagram): ModelElement[] {
  const all = Object.values(project.elements).filter((e) => e.type === "erd-entity");
  if (!diagram) return all;
  const refs = new Set(diagram.views.map((v) => v.ref));
  return all.filter((e) => refs.has(e.id));
}

export function generateDdl(project: Project, dialect: SqlDialect, diagram?: Diagram): string {
  const entities = entitiesOf(project, diagram);
  const ids = new Set(entities.map((e) => e.id));
  const q = (n: string) => quote(dialect, n);
  const out: string[] = [`-- Generated by SlopwareIdeasModeler (${SQL_DIALECTS.find((x) => x.id === dialect)?.name})`, ""];

  for (const e of entities) {
    const attrs = e.erdAttributes ?? [];
    const lines = attrs.map((a) => {
      let s = `  ${q(a.name)} ${columnType(dialect, a)}`;
      if (!a.nullable || a.primaryKey) s += " NOT NULL";
      if (a.autoIncrement && dialect !== "postgresql") {
        if (dialect === "mysql") s += " AUTO_INCREMENT";
        else if (dialect === "mssql") s += " IDENTITY(1,1)";
        else if (dialect === "oracle") s += " GENERATED ALWAYS AS IDENTITY";
      }
      if (a.defaultValue) s += ` DEFAULT ${a.defaultValue}`;
      if (a.unique && !a.primaryKey) s += " UNIQUE";
      return s;
    });
    const pk = attrs.filter((a) => a.primaryKey);
    if (pk.length) lines.push(`  CONSTRAINT ${q("PK_" + e.name)} PRIMARY KEY (${pk.map((a) => q(a.name)).join(", ")})`);
    out.push(`CREATE TABLE ${q(e.name)} (\n${lines.join(",\n")}\n);`, "");
  }

  for (const rel of Object.values(project.elements)) {
    if (rel.type !== "erd-relationship" || !rel.from || !rel.to || !ids.has(rel.from) || !ids.has(rel.to)) continue;
    const parent = project.elements[rel.from];
    const child = project.elements[rel.to];
    let pairs = (rel.erd?.pairs ?? [])
      .map((p) => ({ from: parent.erdAttributes?.find((a) => a.id === p.from), to: child.erdAttributes?.find((a) => a.id === p.to) }))
      .filter((p) => p.from && p.to) as { from: ErdAttribute; to: ErdAttribute }[];
    if (!pairs.length) {
      // Without explicit attribute pairs, match the parent key to a child FK with the conventional name.
      const pk = parent.erdAttributes?.find((a) => a.primaryKey);
      const fk = child.erdAttributes?.find((a) => a.foreignKey && pk && a.name.toLowerCase() === (parent.name + pk.name).toLowerCase());
      if (pk && fk) pairs = [{ from: pk, to: fk }];
    }
    if (!pairs.length) {
      out.push(`-- Relationship ${parent.name} -> ${child.name} has no attribute pairs`);
      continue;
    }
    const name = `FK_${child.name}_${parent.name}`;
    if (dialect === "sqlite") {
      out.push(`-- SQLite needs foreign keys inside CREATE TABLE: FOREIGN KEY (${pairs.map((p) => q(p.to.name)).join(", ")}) REFERENCES ${q(parent.name)} (${pairs.map((p) => q(p.from.name)).join(", ")})`);
      continue;
    }
    out.push(
      `ALTER TABLE ${q(child.name)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${pairs.map((p) => q(p.to.name)).join(", ")}) REFERENCES ${q(parent.name)} (${pairs.map((p) => q(p.from.name)).join(", ")});`,
    );
  }
  return out.join("\n") + "\n";
}
